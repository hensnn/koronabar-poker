/** Vytvoří registr se všemi parametry a pravidly konzistence. */
export function createDefaultRegistry(): SettingsRegistry {
  const reg = new SettingsRegistry().register(...ALL_SETTING_DEFS);
  reg.addRule(
    {
      id: 'blinds',
      keys: ['table.smallBlind', 'table.bigBlind'],
      check: (v) => (v['table.smallBlind'] as number) <= (v['table.bigBlind'] as number),
      messageKey: 'rule.smallBlindAboveBig',
    },
    {
      id: 'buyin',
      keys: ['cash.minBuyInBb', 'cash.maxBuyInBb'],
      check: (v) => (v['cash.minBuyInBb'] as number) <= (v['cash.maxBuyInBb'] as number),
      messageKey: 'rule.minBuyInAboveMax',
    },
    {
      id: 'assistantTimeouts',
      keys: ['assistant.timeoutSeconds', 'assistant.totalTimeoutSeconds'],
      check: (v) => (v['assistant.totalTimeoutSeconds'] as number) >= (v['assistant.timeoutSeconds'] as number),
      messageKey: 'rule.assistantTimeouts',
    },
    {
      id: 'assistantLimits',
      keys: ['assistant.perUserDaily', 'assistant.globalDaily'],
      check: (v) => (v['assistant.globalDaily'] as number) === 0 || (v['assistant.perUserDaily'] as number) === 0 || (v['assistant.perUserDaily'] as number) <= (v['assistant.globalDaily'] as number),
      messageKey: 'rule.assistantLimits',
    },
    {
      id: 'badBeatShares',
      keys: ['jackpot.badBeatLoserShare', 'jackpot.badBeatWinnerShare'],
      check: (v) => (v['jackpot.badBeatLoserShare'] as number) + (v['jackpot.badBeatWinnerShare'] as number) <= 100,
      messageKey: 'rule.badBeatShares',
    },
    {
      id: 'bountyCuts',
      keys: ['tournament.bountyType', 'tournament.bountyPercent', 'tournament.houseCutPercent', 'tournament.fundPercent'],
      check: (v) => (v['tournament.bountyType'] === 'none' ? 0 : (v['tournament.bountyPercent'] as number)) + (v['tournament.houseCutPercent'] as number) + (v['tournament.fundPercent'] as number) <= 100,
      messageKey: 'rule.bountyCutsTooHigh',
    },
    {
      id: 'tournamentCuts',
      keys: ['tournament.houseCutPercent', 'tournament.fundPercent'],
      check: (v) => (v['tournament.houseCutPercent'] as number) + (v['tournament.fundPercent'] as number) <= 50,
      messageKey: 'rule.cutsTooHigh',
    },
    {
      id: 'ante',
      keys: ['table.ante', 'table.bigBlind'],
      check: (v) => (v['table.ante'] as number) <= (v['table.bigBlind'] as number),
      messageKey: 'rule.anteAboveBigBlind',
    },
  );
  return reg;
}
