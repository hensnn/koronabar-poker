export type MessageKey = keyof typeof cs;

/** Dosadí {parametry} do textu. Chybějící klíč vrátí jako text, aby byl v UI vidět. */
export function t(key: string, params?: Record<string, unknown>): string {
  const msg = cs[key] ?? key;
  if (!params) return msg;
  // {name} dosadí hodnotu, {name:ns} ji přeloží přes klíč `ns.hodnota` (např. tvary názvů karet)
  return msg.replace(/\{(\w+)(?::([\w.]+))?\}/g, (_, p: string, ns?: string) => {
    const v = params[p];
    if (v === undefined) return `{${p}}`;
    return ns ? (cs[`${ns}.${String(v)}`] ?? String(v)) : String(v);
  });
}
